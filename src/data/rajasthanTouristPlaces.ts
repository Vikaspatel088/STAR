/**
 * Get all places by city
 */
export function getPlacesByCity(city: string): TouristPlace[] {
  return rajasthanTouristPlaces.filter(place => place.city === city);
}

/**
 * Get all places by category
 */
export function getPlacesByCategory(category: TouristPlaceCategory): TouristPlace[] {
  return rajasthanTouristPlaces.filter(place => place.category === category);
}

/**
 * Get all unique cities
 */
export function getAllCities(): string[] {
  return Array.from(new Set(rajasthanTouristPlaces.map(place => place.city))).sort();
}

/**
 * Get all unique categories
 */
export function getAllCategories(): TouristPlaceCategory[] {
  return Array.from(new Set(rajasthanTouristPlaces.map(place => place.category))).sort();
}

/**
 * Get statistics about tourist places
 */
export function getTouristPlacesStats() {
  return {
    total: rajasthanTouristPlaces.length,
    byCity: getAllCities().reduce((acc, city) => {
      acc[city] = getPlacesByCity(city).length;
      return acc;
    }, {} as Record<string, number>),
    byCategory: getAllCategories().reduce((acc, category) => {
      acc[category] = getPlacesByCategory(category).length;
      return acc;
    }, {} as Record<TouristPlaceCategory, number>),
  };
}
